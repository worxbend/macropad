/// Column bitmaps of a character. Lowercase letters use the capitals; anything else unknown shows `?`.
pub fn glyph(character: char) -> [u8; GLYPH_WIDTH] {
    let upper = character.to_ascii_uppercase();
    let code = if upper.is_ascii() { upper as u8 } else { UNKNOWN };
    let index = code
        .checked_sub(FIRST_CHAR)
        .map(usize::from)
        .filter(|&index| index < GLYPHS.len());
    GLYPHS[index.unwrap_or(usize::from(UNKNOWN - FIRST_CHAR))]
}

/// Width of a string in pixels, without the gap after the last glyph.
pub fn text_width(text: &str) -> usize {
    (text.chars().count() * ADVANCE).saturating_sub(1)
}

/// Width of a string drawn with `Framebuffer::big_text`.
pub fn big_text_width(text: &str, scale: usize) -> usize {
    text_width(text) * scale
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn capital_i_is_a_centred_bar_with_serifs() {
        assert_eq!(glyph('I'), [0x00, 0x41, 0x7F, 0x41, 0x00]);
    }

    #[test]
    fn lowercase_uses_the_capital_glyph() {
        assert_eq!(glyph('a'), glyph('A'));
    }

    #[test]
    fn characters_outside_the_table_show_a_question_mark() {
        for outside in ['\n', '~', 'é', '\u{1F600}'] {
            assert_eq!(glyph(outside), glyph('?'), "{outside:?}");
        }
    }

    #[test]
    fn table_edges_are_reachable() {
        assert_eq!(glyph(' '), [0; GLYPH_WIDTH]);
        assert_eq!(glyph('_'), [0x40; GLYPH_WIDTH]);
    }

    #[test]
    fn text_width_has_no_trailing_gap() {
        assert_eq!(text_width(""), 0);
        assert_eq!(text_width("A"), 5);
        assert_eq!(text_width("AB"), 11);
    }

    #[test]
    fn big_text_width_scales_the_gaps_too() {
        assert_eq!(big_text_width("AB", 3), 33);
    }
}
